"""Load base model and tokenizer, inspect architecture, and log memory footprint."""
from __future__ import annotations

import json
import sys
from pathlib import Path

# Bootstrap: make scripts/ importable regardless of CWD
SCRIPTS_DIR = Path(__file__).resolve().parent
if str(SCRIPTS_DIR) not in sys.path:
    sys.path.insert(0, str(SCRIPTS_DIR))

from common import SEED, TRACK_DIR, dump_config, set_seed  # noqa: E402
from config import CLEAN_TXT, MODEL_ARCH_JSON, MODEL_CHOICE_MD, STATS_JSON  # noqa: E402

MODEL_NAME = "HuggingFaceTB/SmolLM2-135M"
T4_VRAM_GB = 15.0

def main() -> None:
    seed = set_seed(SEED)
    print(f"[phase2] seed = {seed}")

    # Load tokenizer
    print(f"\n[phase2] loading tokenizer: {MODEL_NAME}")
    from transformers import AutoModelForCausalLM, AutoTokenizer

    tokenizer = AutoTokenizer.from_pretrained(MODEL_NAME)
    print(f"[phase2] vocab size: {tokenizer.vocab_size:,}")

    # Pad token decision
    if tokenizer.pad_token is None:
        tokenizer.pad_token = tokenizer.eos_token
        pad_token_decision = (
            f"pad_token was None — set to eos_token ('{tokenizer.eos_token}', "
            f"id={tokenizer.eos_token_id}). "
            "DOWNSTREAM NOTE (Phase 5): data collator MUST mask pad positions in "
            "labels (labels=-100 at pad positions). Failure to do so trains the "
            "model on <eos> as content signal."
        )
        print(f"[phase2] pad_token set -> eos_token: '{tokenizer.eos_token}'")
    else:
        pad_token_decision = (
            f"pad_token already set: '{tokenizer.pad_token}' "
            f"(id={tokenizer.pad_token_id}). No override needed. "
            "DOWNSTREAM NOTE (Phase 5): data collator MUST still mask pad positions "
            "in labels (labels=-100 at pad positions) regardless of token source."
        )
        print(f"[phase2] pad_token already set: '{tokenizer.pad_token}'")

    # Load model
    print(f"\n[phase2] loading model: {MODEL_NAME} ...")
    model = AutoModelForCausalLM.from_pretrained(MODEL_NAME)
    total_params = sum(p.numel() for p in model.parameters())
    print(f"[phase2] total parameters: {total_params:,}")

    # Architecture verification — save ALL module names now
    all_module_names = [n for n, _ in model.named_modules() if n]  # skip root ""
    arch_record = {
        "model_name": MODEL_NAME,
        "total_params": total_params,
        "all_module_names": all_module_names,
        "note": (
            "Generated by select_model.py (Phase 2). "
            "Use this list in Phase 4 to set LoraConfig.target_modules from "
            "*verified* layer names. Filter for 'q_proj', 'k_proj', 'v_proj', "
            "'o_proj' (or 'c_attn' for GPT-2-style fused projections) to identify "
            "attention projection layers."
        ),
    }
    MODEL_ARCH_JSON.parent.mkdir(parents=True, exist_ok=True)
    MODEL_ARCH_JSON.write_text(json.dumps(arch_record, indent=2) + "\n", encoding="utf-8")
    print(f"[phase2] full module list ({len(all_module_names)} names) saved -> {MODEL_ARCH_JSON}")

    # Print filtered view of attention modules for immediate spot-check
    attention_keywords = ("q_proj", "k_proj", "v_proj", "o_proj", "c_attn", "attn")
    attn_modules = [n for n in all_module_names if any(kw in n for kw in attention_keywords)]
    print(f"[phase2] attention-related modules ({len(attn_modules)} found):")
    for name in attn_modules[:40]:  # cap output length
        print(f"  {name}")
    if len(attn_modules) > 40:
        print(f"  ... ({len(attn_modules) - 40} more — see model_architecture.json)")

    # Re-tokenize document_clean.txt with real tokenizer
    print(f"\n[phase2] tokenizing {CLEAN_TXT} ...")
    text = CLEAN_TXT.read_text(encoding="utf-8")
    token_ids = tokenizer.encode(text, add_special_tokens=False)
    exact_token_count = len(token_ids)
    print(f"[phase2] exact token count ({MODEL_NAME}): {exact_token_count:,}")

    # Update stats.json — ADD new field, preserve all existing
    stats = json.loads(STATS_JSON.read_text(encoding="utf-8"))
    proxy_count = stats.get("proxy_token_count_gpt2_tiktoken")
    stats["exact_token_count_smollm2_135m"] = exact_token_count
    if proxy_count is not None:
        delta_pct = (exact_token_count - proxy_count) / proxy_count * 100
        stats["note_phase2_token_count"] = (
            f"exact_token_count_smollm2_135m = {exact_token_count:,} "
            f"({delta_pct:+.1f}% vs proxy_token_count_gpt2_tiktoken={proxy_count:,}). "
            "proxy field preserved for audit trail."
        )
        print(
            f"[phase2] proxy count was {proxy_count:,}; real count is {exact_token_count:,} "
            f"({delta_pct:+.1f}%)"
        )
    STATS_JSON.write_text(json.dumps(stats, indent=2) + "\n", encoding="utf-8")
    print(f"[phase2] stats.json updated -> {STATS_JSON}")

    # Quantization decision — memory math
    fp16_bytes = total_params * 2
    fp16_mb = fp16_bytes / 1_000_000
    vram_utilisation_pct = fp16_mb / (T4_VRAM_GB * 1000) * 100
    quantization_decision = (
        f"No quantization needed. "
        f"Frozen-weight fp16 footprint: {fp16_mb:.0f} MB "
        f"({total_params:,} params × 2 bytes = {fp16_bytes:,} bytes), "
        f"{vram_utilisation_pct:.1f}% of T4 VRAM ({T4_VRAM_GB} GB). "
        "NOTE: this covers frozen-weight storage only. Full training memory "
        "also includes activations, gradients, and optimizer state for the "
        "LoRA-trainable parameter slice. At this model size with LoRA "
        "(typically ~0.5–2% of parameters), the additional overhead is small "
        "but should be confirmed empirically once Phase 5 batch size is set "
        "(check torch.cuda.max_memory_allocated() after the first training step)."
    )
    print(f"\n[phase2] quantization: no quantization needed")
    print(f"[phase2] fp16 weight footprint: {fp16_mb:.0f} MB ({vram_utilisation_pct:.1f}% of T4 VRAM)")
    print(f"[phase2] memory caveat: footprint is weights-only — empirically verify in Phase 5")

    # Dump run config
    run_config = {
        "phase": 2,
        "model_name": MODEL_NAME,
        "total_params": total_params,
        "tokenizer_vocab_size": tokenizer.vocab_size,
        "pad_token": tokenizer.pad_token,
        "pad_token_id": tokenizer.pad_token_id,
        "pad_token_decision": pad_token_decision,
        "exact_token_count_smollm2_135m": exact_token_count,
        "proxy_token_count_gpt2_tiktoken": proxy_count,
        "fp16_weight_footprint_mb": round(fp16_mb, 1),
        "t4_vram_gb": T4_VRAM_GB,
        "vram_utilisation_weights_only_pct": round(vram_utilisation_pct, 2),
        "quantization_needed": False,
        "quantization_decision": quantization_decision,
        "model_architecture_json": str(MODEL_ARCH_JSON),
    }
    cfg_path = dump_config(run_config, "phase2")
    print(f"[phase2] run config saved -> {cfg_path}")

    # Definition-of-Done assertions
    updated_stats = json.loads(STATS_JSON.read_text(encoding="utf-8"))
    assert "exact_token_count_smollm2_135m" in updated_stats, (
        "FAIL: stats.json missing exact_token_count_smollm2_135m"
    )
    assert MODEL_ARCH_JSON.exists(), "FAIL: model_architecture.json not written"
    assert cfg_path.exists(), f"FAIL: run config not saved at {cfg_path}"
    print("\n[phase2] [OK] all Definition-of-Done assertions passed")
    print("[phase2] Phase 2 complete. Review configs/ and data/extracted/stats.json, then commit.")

if __name__ == "__main__":
    main()
